std::string read_cpu_model()
{
#ifdef __APPLE__
    // No /proc on macOS; the brand string lives in sysctl.
    std::size_t len = 0;
    if (sysctlbyname("machdep.cpu.brand_string", NULL, &len, NULL, 0) != 0 || len == 0)
        return "unknown";
    std::string model(len, '\0');
    if (sysctlbyname("machdep.cpu.brand_string", &model[0], &len, NULL, 0) != 0)
        return "unknown";
    // len counts the trailing NUL, which does not belong in a std::string.
    model.resize(len > 0 ? len - 1 : 0);
    return model.empty() ? "unknown" : model;
#else
    std::ifstream cpuinfo("/proc/cpuinfo");
    if (!cpuinfo) return "unknown";

    std::string line;
    while (std::getline(cpuinfo, line)) {
        const std::size_t pos = line.find("model name");
        if (pos == std::string::npos) continue;
        const std::size_t colon = line.find(':', pos);
        if (colon == std::string::npos) continue;
        std::string model = line.substr(colon + 1);
        while (!model.empty() && std::isspace(static_cast<unsigned char>(model.front())))
            model.erase(model.begin());
        if (!model.empty()) return model;
    }
    return "unknown";
#endif
}

// %FT%TZ in UTC; "unknown" on failure -- strftime leaves the buffer indeterminate.
std::string utc_stamp(std::time_t t)
{
    char stamp[32];
    if (const std::tm* utc = std::gmtime(&t))
        if (std::strftime(stamp, sizeof(stamp), "%Y-%m-%dT%H:%M:%SZ", utc) > 0)
            return stamp;
    return "unknown";
}

// Link time: the executable's own mtime. The embedded block cannot carry it --
// writing a timestamp into the binary would change the binary.
std::string exe_mtime_utc()
{
    char path[4096];   // Linux PATH_MAX; an over-long path degrades to "unknown"
#if defined(__APPLE__)
    uint32_t size = sizeof(path);
    if (_NSGetExecutablePath(path, &size) != 0) return "unknown";
#elif defined(__linux__)
    const ssize_t n = readlink("/proc/self/exe", path, sizeof(path) - 1);
    if (n <= 0) return "unknown";
    path[n] = '\0';
#else
    return "unknown";
#endif
#ifndef WIN32
    struct stat st;
    if (stat(path, &st) != 0) return "unknown";
    return utc_stamp(st.st_mtime);
#endif
}

