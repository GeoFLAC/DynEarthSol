// -1, 0 or "" for a key this hardware lacks, e.g. hw.perflevel* on Intel Macs.
int sysctl_int32(const char* name)
{
    int32_t value = 0;
    std::size_t len = sizeof(value);
    if (sysctlbyname(name, &value, &len, NULL, 0) != 0 || len != sizeof(value))
        return -1;
    return value;
}

uint64_t sysctl_uint64(const char* name)
{
    uint64_t value = 0;
    std::size_t len = sizeof(value);
    if (sysctlbyname(name, &value, &len, NULL, 0) != 0 || len != sizeof(value))
        return 0;
    return value;
}

std::string sysctl_string(const char* name)
{
    std::size_t len = 0;
    if (sysctlbyname(name, NULL, &len, NULL, 0) != 0 || len == 0)
        return std::string();
    std::string value(len, '\0');
    if (sysctlbyname(name, &value[0], &len, NULL, 0) != 0)
        return std::string();
    // len counts the trailing NUL, which does not belong in a std::string.
    value.resize(len > 0 ? len - 1 : 0);
    return value;
}
