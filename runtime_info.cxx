// What other processes left, not a host property: free+speculative+inactive on macOS
// (free_count already counts the speculative pages vm_stat prints apart), MemAvailable
// on Linux. Not comparable across the two -- macOS counts dirty pages Linux withholds.
double host_mem_avail_gib_now()
{
#if defined(__APPLE__)
    // mach_host_self() hands out a send right we own, unlike mach_task_self().
    const mach_port_t self = mach_host_self();
    vm_size_t page = 0;
    vm_statistics64_data_t vm;
    mach_msg_type_number_t count = HOST_VM_INFO64_COUNT;
    const bool ok = host_page_size(self, &page) == KERN_SUCCESS &&
                    host_statistics64(self, HOST_VM_INFO64,
                                      reinterpret_cast<host_info64_t>(&vm),
                                      &count) == KERN_SUCCESS;
    mach_port_deallocate(mach_task_self(), self);
    if (!ok) return 0;
    return (static_cast<double>(vm.free_count) + vm.inactive_count) * page /
           (1024.0 * 1024.0 * 1024.0);
#elif defined(__linux__)
    return read_proc_meminfo_gib("MemAvailable");
#else
    return 0;
#endif
}

double host_mem_rss_gib()
{
#if defined(__APPLE__)
    mach_task_basic_info info;
    mach_msg_type_number_t count = MACH_TASK_BASIC_INFO_COUNT;
    if (task_info(mach_task_self(), MACH_TASK_BASIC_INFO,
                  reinterpret_cast<task_info_t>(&info), &count) != KERN_SUCCESS)
        return 0;
    return static_cast<double>(info.resident_size) / (1024.0 * 1024.0 * 1024.0);
#elif defined(__linux__)
    return read_proc_self_rss_gib();
#else
    return 0;
#endif
}

// Peak resident set: the high-water mark, so a spike between two frames is not
// missed by the instantaneous sample. ru_maxrss is bytes on macOS, kilobytes on Linux.
// Floored at the live resident set: on Linux ru_maxrss is mm->hiwater_rss, which the
// kernel refreshes only at its own call sites and which therefore trails VmRSS -- half of
// one host's frames reported a "peak" below the rss in the same record. The floor makes
// this a lower bound, not a high-water mark: it falls with the rss once the live value
// has overtaken a stale ru_maxrss, so the caller keeps the running maximum.
double host_peak_rss_gib()
{
#ifndef WIN32
    struct rusage ru;
    if (getrusage(RUSAGE_SELF, &ru) != 0) return 0;
#if defined(__APPLE__)
    const double peak = static_cast<double>(ru.ru_maxrss) / (1024.0 * 1024.0 * 1024.0);
#else
    const double peak = static_cast<double>(ru.ru_maxrss) / (1024.0 * 1024.0);
#endif
    return std::max(peak, host_mem_rss_gib());
#else
    return 0;
#endif
}

// CPU seconds this process has burned, user + system. Against the frame's
// walltime_sec and omp_threads it gives the parallel efficiency, so a stalling
// region or an oversubscribed host shows up as a falling ratio.
double process_cpu_time_sec()
{
#ifndef WIN32
    struct rusage ru;
    if (getrusage(RUSAGE_SELF, &ru) != 0) return 0;
    return ru.ru_utime.tv_sec + ru.ru_utime.tv_usec * 1e-6
         + ru.ru_stime.tv_sec + ru.ru_stime.tv_usec * 1e-6;
#else
    return 0;
#endif
}

// One-minute load average: contention from everything else on the machine, which
// is what separates "the model slowed down" from "the machine got busy".
double host_load_avg_1m()
{
#ifndef WIN32
    double la[1] = {0};
    if (getloadavg(la, 1) != 1) return 0;
    return la[0];
#else
    return 0;
#endif
}

double device_mem_used_dev_gib(const DeviceInfo& dev)
{
#ifdef ACC
    if (dev.using_gpu && dev.mem_total_gib > 0) {
        const acc_device_t type = acc_get_device_type();
        const size_t free_now =
            acc_get_property(acc_get_device_num(type), type, acc_property_free_memory);
        if (free_now)
            return dev.mem_total_gib -
                   static_cast<double>(free_now) / (1024.0 * 1024.0 * 1024.0);
    }
#else
    (void)dev;
#endif
    return 0;
}

BuildInfo probe_build_info()
{
    BuildInfo b;

    // Identity restated as fields so the frame writer never parses the sentinel text.
    // Build CONFIGURATION is deliberately NOT restated: it reaches a reader through the
    // block's own options/toolchain/defines lines.
    b.rev = DES_REVISION;
    b.branch = DES_BRANCH;
    const std::string dirty(DES_DIRTY);   // " dirty=2f/+13/-12"/" dirty=unknown", "" = clean
    const std::size_t eq = dirty.find('=');
    b.dirty = (eq == std::string::npos) ? "clean" : dirty.substr(eq + 1);
    b.origin = DES_ORIGIN;
    b.state_utc = DES_STATE_UTC;
    b.build_os = DES_BUILD_OS;
    b.builder = DES_BUILDER;
    b.exe_mtime_utc = exe_mtime_utc();

    return b;
}


CpuInfo probe_cpu_info(bool wait_policy_from_des)
{
    CpuInfo cpu;
    cpu.model = "unknown";
    cpu.logical_cores = -1;
    cpu.physical_cores = -1;
    cpu.perf_cores = -1;
    cpu.eff_cores = -1;
    cpu.mem_total_gib = 0;
    cpu.mem_avail_gib = 0;
    cpu.openmp_enabled = false;
    cpu.omp_team_size = -1;
    cpu.omp_max_threads = -1;
    cpu.omp_num_procs = -1;
    cpu.omp_dynamic = false;

    cpu.os = runtime_os();
    cpu.runner = runner_id();
    cpu.mem_avail_gib = host_mem_avail_gib_now();

    const unsigned int hw_threads = std::thread::hardware_concurrency();
    if (hw_threads) cpu.logical_cores = static_cast<int>(hw_threads);

#ifdef __APPLE__
    const std::string brand = sysctl_string("machdep.cpu.brand_string");
    if (!brand.empty()) cpu.model = brand;
    else {
        const std::string hw_model = sysctl_string("hw.model");
        if (!hw_model.empty()) cpu.model = hw_model;
    }
    cpu.physical_cores = sysctl_int32("hw.physicalcpu");
    const int logical = sysctl_int32("hw.logicalcpu");
    if (logical > 0) cpu.logical_cores = logical;
    // Only a two-tier part maps onto perf/eff; a third tier leaves eff unknown rather
    // than silently naming tier 1 the whole efficiency side.
    cpu.perf_cores = sysctl_int32("hw.perflevel0.physicalcpu");
    if (sysctl_int32("hw.nperflevels") == 2)
        cpu.eff_cores = sysctl_int32("hw.perflevel1.physicalcpu");
    const uint64_t memsize = sysctl_uint64("hw.memsize");
    if (memsize) cpu.mem_total_gib = static_cast<double>(memsize) /
                                    (1024.0 * 1024.0 * 1024.0);
#elif defined(__linux__)
    // /proc/cpuinfo first so x86 hosts report what they did before, then sysfs.
    std::string model, arm_implementer, arm_part;
    read_proc_cpuinfo(model, cpu.physical_cores, arm_implementer, arm_part);
    if (cpu.physical_cores < 0) cpu.physical_cores = read_sysfs_physical_cores();

    // Name the host from whichever source answers, chip first then machine: ARM boards
    // publish a device-tree model, servers and cloud instances publish DMI strings.
    if (model.empty()) model = read_first_line("/proc/device-tree/model");
    if (model.empty()) model = read_dmi_model();
    if (model.empty() && !arm_implementer.empty() && !arm_part.empty()) {
        // Last resort on an anonymous ARM core: the raw ids identify it to a human. NOT
        // decoded to a name -- a part-number table would go stale with every new core.
        struct utsname uts;
        const std::string machine = (uname(&uts) == 0) ? uts.machine : "";
        model = machine + (machine.empty() ? "" : " ") +
                "(CPU implementer " + arm_implementer +
                ", part " + arm_part + ")";
    }
    if (!model.empty()) cpu.model = model;
    cpu.mem_total_gib = read_proc_meminfo_gib("MemTotal");
#endif

#ifdef _OPENMP
    cpu.openmp_enabled = true;
    cpu.omp_max_threads = omp_get_max_threads();
    cpu.omp_num_procs = omp_get_num_procs();
    cpu.omp_dynamic = (omp_get_dynamic() != 0);
    cpu.omp_team_size = measure_omp_team_size();
#endif

    // Non-empty, matching what omp_wait_policy_eff acts on: a variable exported empty
    // governs nothing, so calling it "env" would claim a policy beside eff's "default".
    const char* const wp = std::getenv("OMP_WAIT_POLICY");
    const char* const bt = std::getenv("KMP_BLOCKTIME");
    if (wait_policy_from_des)
        cpu.wait_policy_src = "des-default";
    else if ((wp && *wp) || (bt && *bt))
        cpu.wait_policy_src = "env";
    else
        cpu.wait_policy_src = "runtime";

    return cpu;
}

Manifest compose_manifest(const Param& param, const BuildInfo& build,
                          const CpuInfo& cpu, const DeviceInfo& dev)
{
    Manifest m;
    Fields run;
    add(run, "modelname", param.sim.modelname);
    add(run, "restarting", param.sim.is_restarting ? "yes" : "no");
    if (param.sim.is_restarting) {
        add(run, "restart_from_model", param.sim.restarting_from_modelname);
        add(run, "restart_from_frame", std::to_string(param.sim.restarting_from_frame));
    }
    add(run, "start_utc", utc_now());
    add_section(m, "runtime.model", run);

    // The host this run got, run-side counterpart of the block's host line.
    Fields host;
    add(host, "os", cpu.os);
    add(host, "runner", cpu.runner);
    add(host, "cpu_model", cpu.model);
    add(host, "physical_cores", int_or_unknown(cpu.physical_cores));
    add(host, "logical_cores", int_or_unknown(cpu.logical_cores));
    add(host, "perf_cores", int_or_unknown(cpu.perf_cores));
    add(host, "eff_cores", int_or_unknown(cpu.eff_cores));
    add(host, "mem_total_gib", gib_or_unknown(cpu.mem_total_gib));
    // A snapshot of what other processes left, not comparable across runs.
    add(host, "mem_avail_at_start_gib", gib_or_unknown(cpu.mem_avail_gib));
    add_section(m, "runtime.host", host);

    // The device: an openacc=1 binary silently falls back to the host when it finds no
    // NVIDIA device, so the build alone does not say where the arithmetic happened.
    Fields device;
    add(device, "kernel", dev.kernel);
    // Before the using_gpu block: a run that found no device writes this manifest and
    // nothing else, and an empty filter -- "none" -- is why it found none.
    if (dev.acc_build)
        add(device, "visible_devices", dev.visible_devices);
    if (dev.using_gpu) {
        if (!dev.name.empty()) add(device, "name", dev.name);
        add(device, "selected", std::to_string(dev.active_dev) + "/"
                              + std::to_string(dev.num_devices));
        if (!dev.cuda_driver.empty()) add(device, "cuda_driver", dev.cuda_driver);
        add(device, "mem_total_gib", gib_or_unknown(dev.mem_total_gib));
        add(device, "mem_free_at_start_gib", gib_or_unknown(dev.mem_free_gib));
    }
    add_section(m, "runtime.device", device);

    Fields threads;
    add(threads, "openmp", cpu.openmp_enabled ? "enabled" : "disabled");
    if (cpu.openmp_enabled) {
        add(threads, "omp_threads", int_or_unknown(cpu.omp_team_size));
        add(threads, "omp_max_threads", int_or_unknown(cpu.omp_max_threads));
        add(threads, "omp_num_procs", int_or_unknown(cpu.omp_num_procs));
        add(threads, "omp_dynamic", cpu.omp_dynamic ? "on" : "off");
        // Names what was set, not one resolved policy: libomp lets KMP_BLOCKTIME set the
        // spin time whenever it is set and OMP_WAIT_POLICY only the library mode, so
        // either alone asserts the wrong thing when both are. Measured: libgomp and
        // nvomp honour OMP_WAIT_POLICY and ignore KMP_BLOCKTIME entirely, so on those
        // the blocktime term records an intent the runtime did not act on.
        // Always emitted: absent would read as "not probed".
        std::string policy;
        if (const char* wait = std::getenv("OMP_WAIT_POLICY"))
            if (*wait) policy = wait;
        if (const char* bt = std::getenv("KMP_BLOCKTIME"))
            if (*bt) policy += (policy.empty() ? "" : "+") + std::string("blocktime=") + bt;
        add(threads, "omp_wait_policy_eff", policy.empty() ? "default" : policy);
        add(threads, "omp_wait_policy_src", cpu.wait_policy_src);
    }
    add_section(m, "runtime.threads", threads);

    // Only the variables that are set: an unset entry carries no information, and the
    // effective values they steer are all recorded above.
    const char* const env_names[] = {
        "OMP_NUM_THREADS", "OMP_THREAD_LIMIT", "OMP_DYNAMIC", "OMP_PROC_BIND",
        // Listed on every platform: it is set by the time this runs, and on macOS main()
        // is what set it -- so a manifest that omitted it would hide a variable the run
        // had. Which of the two set it follows from the rule main() prints: on macOS,
        // active with no KMP_BLOCKTIME beside it is DES's own default.
        "OMP_PLACES", "OMP_WAIT_POLICY", "KMP_BLOCKTIME",
    };
    // The device-selection variables, measured to move a run between physical cards.
    // Only on an ACC build: elsewhere they steer nothing and read as if they had.
    const char* const acc_env_names[] = {
        "CUDA_VISIBLE_DEVICES", "ACC_DEVICE_TYPE", "ACC_DEVICE_NUM",
        "NVCOMPILER_ACC_DEVICE_TYPE", "NVCOMPILER_ACC_DEVICE_NUM"
    };
    Fields env;
    for (std::size_t i = 0; i < sizeof(env_names) / sizeof(env_names[0]); ++i)
        if (const char* v = std::getenv(env_names[i]))
            add(env, env_names[i], v);
    if (dev.acc_build)
        for (std::size_t i = 0; i < sizeof(acc_env_names) / sizeof(acc_env_names[0]); ++i)
            if (const char* v = std::getenv(acc_env_names[i]))
                add(env, acc_env_names[i], v);
    add_section(m, "runtime.env", env);

    // The embedded build.snapshot block, re-expressed as sections: the binary's
    // literal stays the single source of truth. exe_mtime_utc joins its host line here
    // because the block cannot carry its own link time; the host line closes the
    // block, so appending the pair before parsing files it in the right section.
    const std::string block = std::string(snapshot_sentinel)
                            + " exe_mtime_utc=" + build.exe_mtime_utc;
    std::istringstream blocklines(block);
    std::string line;
    Fields compile, link, other;        // the bare-flag-list topics, by stage
    while (std::getline(blocklines, line)) {
        const std::size_t sep = line.find(" : ");
        if (sep == std::string::npos) {
            // Unreachable today (every topic has an unconditional member), but the
            // payloads are preprocessor-assembled: keep the line rather than lose it.
            add(other, "unparsed", line);
            continue;
        }
        std::string topic = line.substr(0, sep);
        const std::size_t dot = topic.rfind('.');
        if (dot != std::string::npos) topic = topic.substr(dot + 1);
        while (!topic.empty() && topic[topic.size() - 1] == ' ')   // column padding
            topic.erase(topic.size() - 1);

        const std::string payload = line.substr(sep + 3);
        const Fields fields = parse_block_payload(payload);
        if (fields.empty()) {
            // A bare flag list, filed by the stage that saw it: compile flags reach
            // every .o, link flags the executable alone -- the link rule passes LDFLAGS
            // and never CXXFLAGS. defines and warnings are compile-side too.
            if (topic == "link")         add(link, "flags", payload);
            else if (topic == "compile") add(compile, "flags", payload);
            else                         add(compile, topic, payload);
        }
        else
            add_section(m, "build." + topic, fields);
    }
    add_section(m, "build.compile", compile);
    add_section(m, "build.link", link);
    add_section(m, "build.unparsed", other);
    return m;
}

void write_manifest(const Param& param, const Manifest& manifest, bool keep_existing)
{
    const std::string filename(param.sim.modelname + ".manifest");

    // Appended on a restart, so a resume onto another host stays readable; truncated on a
    // fresh run, matching .info, since re-running a model name replaces its frames. A run
    // that is about to fail appends instead: it replaces no frames, so it must not replace
    // the record of the run whose frames are still there.
    const bool append = param.sim.is_restarting || keep_existing;
    std::FILE* f = std::fopen(filename.c_str(), append ? "a" : "w");
    if (f == NULL) {
        // Provenance is diagnostic-only -- it must never abort a run.
        std::cerr << "Warning: cannot open file '" << filename
                  << "' for writing; run provenance not recorded\n";
        return;
    }

    // An appended record needs a visible seam; [runtime.model] restarting= tells the records apart.
    // Guarded on ftell: a restart into a directory with no manifest writes the FIRST record.
    std::fseek(f, 0, SEEK_END);
    if (append && std::ftell(f) > 0)
        std::fprintf(f, keep_existing
                        ? "# ---- a run that could not start follows ----\n\n"
                        : "# ---- restart: another record follows ----\n\n");

    for (std::size_t i = 0; i < manifest.size(); ++i)
        write_section(f, manifest[i].name, manifest[i].fields);

#ifdef DES_HAS_CODE_DIFF
    // The embedded payload, verbatim and fenced, so one sed recipe reads it out of
    // the manifest and out of the binary. Last, because it is the only unbounded
    // part of the record (1 MB cap) and the only part that is not INI.
    std::fprintf(f, "%s\n", snapshot_code_diff);
#else
    // Stated, not left to a missing section: "not built with it" and "built with it and
    // the tree was clean" must not look alike. A comment, so no parser reads it as a key.
    std::fprintf(f, "# build.code-changes: not embedded"
                    " -- this binary was built without snapshot_diff=1\n");
#endif

    // Check the error flag AND fclose: the record is smaller than the stdio buffer, so
    // on a full disk ferror still reads clean while fclose fails and the record is lost.
    const bool write_failed = (std::ferror(f) != 0);
    const bool close_failed = (std::fclose(f) != 0);
    if (write_failed || close_failed)
        std::cerr << "Warning: failed writing to file '" << filename
                  << "'; run provenance may be incomplete\n";
}

// The only place the device is CHOSEN -- never skip or reorder it;
// report_build_and_runtime_info() below only prints. mem_free is sampled here at
// selection time: a snapshot of what other processes left, not a device property.
DeviceInfo init_offload_device()
{
    DeviceInfo dev;
    dev.acc_build = false;
    dev.using_gpu = false;
    dev.kernel = "CPU";
    dev.num_devices = 0;
    dev.active_dev = -1;
    dev.mem_total_gib = 0;
    dev.mem_free_gib = 0;

#ifdef ACC
    dev.acc_build = true;

    // Read here, not at write time: it is what selected the device below, and an empty
    // value hides every one of them -- the case the field most has to distinguish.
    const char* visible = std::getenv("CUDA_VISIBLE_DEVICES");
    dev.visible_devices = !visible ? "all" : (*visible ? visible : "none");

    const int n_nvidia = acc_get_num_devices(acc_device_nvidia);
    dev.num_devices = n_nvidia;

    acc_device_t forced = acc_device_default;
    const bool forced_by_env =
        env_forces_device(std::getenv("ACC_DEVICE_TYPE"), forced) ||
        env_forces_device(std::getenv("NVCOMPILER_ACC_DEVICE_TYPE"), forced);

    if (forced_by_env) {
        acc_set_device_type(forced);
        acc_init(forced);
    }
    else if (n_nvidia > 0) {
        acc_set_device_type(acc_device_nvidia);
        acc_init(acc_device_nvidia);
    }
    else {
        acc_set_device_type(acc_device_host);
        acc_init(acc_device_host);
    }

    const acc_device_t active_type = acc_get_device_type();
    const int active_dev = acc_get_device_num(active_type);
    dev.using_gpu = (active_type == acc_device_nvidia && n_nvidia > 0);
    dev.kernel = dev.using_gpu ? "GPU" : "CPU";
    dev.active_dev = dev.using_gpu ? active_dev : -1;

    const char* name = acc_get_property_string(active_dev, active_type, acc_property_name);
    const char* vendor = acc_get_property_string(active_dev, active_type, acc_property_vendor);
    const char* driver = acc_get_property_string(active_dev, active_type, acc_property_driver);
    if (name) dev.name = name;
    if (vendor) dev.vendor = vendor;
    if (driver) dev.cuda_driver = driver;

    const size_t mem_total = acc_get_property(active_dev, active_type, acc_property_memory);
    if (mem_total)
        dev.mem_total_gib = static_cast<double>(mem_total) / (1024.0 * 1024.0 * 1024.0);
    const size_t mem_free = acc_get_property(active_dev, active_type, acc_property_free_memory);
    if (mem_free)
        dev.mem_free_gib = static_cast<double>(mem_free) / (1024.0 * 1024.0 * 1024.0);
#endif

    return dev;
}

// "[group][topic] key=value, ..." for the section "group.topic".
static void print_section(const ManifestSection& sec)
{
    const std::size_t dot = sec.name.find('.');
    std::cout << '[' << sec.name.substr(0, dot) << ']'
              << '[' << (dot == std::string::npos ? "" : sec.name.substr(dot + 1)) << ']';
    for (std::size_t k = 0; k < sec.fields.size(); ++k)
        std::cout << (k ? ", " : " ") << sec.fields[k].first << '=' << sec.fields[k].second;
    std::cout << '\n';
}

void report_build_and_runtime_info(const Manifest& manifest)
{
    // Build first, then runtime: what the binary is, then what it ran on. The file
    // keeps the manifest's own order.
    const std::string groups[] = { "build.", "runtime." };
    for (std::size_t g = 0; g < 2; ++g) {
        for (std::size_t i = 0; i < manifest.size(); ++i)
            if (manifest[i].name.compare(0, groups[g].size(), groups[g]) == 0)
                print_section(manifest[i]);
        if (g == 0) {
            // The manifest's own closing line, in the same words.
#ifdef DES_HAS_CODE_DIFF
            std::cout << "[build][code-changes] embedded -- see -h for the extraction\n";
#else
            std::cout << "[build][code-changes] not embedded"
                         " -- this binary was built without snapshot_diff=1\n";
#endif
        }
    }
}

