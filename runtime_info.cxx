std::string read_hostname()
{
#ifndef WIN32
    char buf[256];
    if (gethostname(buf, sizeof(buf)) == 0) {
        buf[sizeof(buf)-1] = '\0';
        return std::string(buf);
    }
#endif
    return "unknown";
}

// local_now()'s format for any instant; "unknown" on failure, since strftime then
// leaves the buffer indeterminate.
std::string local_stamp(std::time_t t)
{
    char stamp[64];   // 24 fixed chars, a space, the zone: a zone over ~38 reads "unknown"
    const std::tm* local = std::localtime(&t);
    if (!local || std::strftime(stamp, sizeof(stamp), "%Y-%m-%dT%H:%M:%S%z %Z", local) == 0)
        return "unknown";
    // %z prints -0500 (GNU's %:z is not portable) or nothing; its sign follows the 19
    // chars of "YYYY-MM-DDTHH:MM:SS", and the colon goes after the hour.
    const std::size_t sign = 19;
    std::string s(stamp);
    if (s.size() > sign + 3 && (s[sign] == '+' || s[sign] == '-'))
        s.insert(sign + 3, 1, ':');
    return s;
}

// The executable's mtime: a timestamp embedded in the binary would change the binary.
std::string read_exe_mtime()
{
    char path[4096];   // Linux PATH_MAX; an over-long path degrades to "unknown"
#if defined(__APPLE__)
    uint32_t size = sizeof(path);
    if (_NSGetExecutablePath(path, &size) != 0) return "unknown";
#elif defined(__linux__)
    const ssize_t n = readlink("/proc/self/exe", path, sizeof(path) - 1);
    if (n <= 0) return "unknown";
    path[n] = '\0';
#else
    return "unknown";
#endif
#ifndef WIN32
    struct stat st;
    if (stat(path, &st) != 0) return "unknown";
    return local_stamp(st.st_mtime);
#endif
}

// The run host's OS, same labeling as the build-side DES_BUILD_OS.
std::string runtime_os()
{
#if defined(__APPLE__)
    const std::string version = sysctl_string("kern.osproductversion");
    return version.empty() ? "macos" : "macos-" + version;
#elif defined(__linux__)
    const std::string os = read_os_release();
    return os.empty() ? "linux" : os;
#else
    return "unknown";
#endif
}

// user@host, the run-side counterpart of the build's builder=.
std::string runner_id()
{
    std::string user;
#ifndef WIN32
    if (const struct passwd* pw = getpwuid(geteuid()))
        if (pw->pw_name) user = pw->pw_name;
#endif
    if (user.empty()) {
        const char* env_user = std::getenv("USER");
        user = env_user ? env_user : "unknown";
    }
    return user + "@" + read_hostname();
}


