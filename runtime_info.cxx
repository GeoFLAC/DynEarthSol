{
    return (v >= 0) ? std::to_string(v) : std::string("unknown");
}

// %.1f for the manifest and the screen; the frame writes the same doubles at full
// precision, so the two artifacts round differently by design.
std::string gib_or_unknown(double gib)
{
    if (gib <= 0) return "unknown";
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%.1f", gib);
    return buf;
}

