std::string int_or_unknown(int v)
{
    return (v >= 0) ? std::to_string(v) : std::string("unknown");
}

std::string format_double(const char* spec, double v)
{
    char buf[32];
    std::snprintf(buf, sizeof(buf), spec, v);
    return buf;
}

// %.1f in the start record and on screen; frames keep the full precision.
std::string gib_or_unknown(double gib)
{
    return (gib > 0) ? format_double("%.1f", gib) : std::string("unknown");
}

// The variable's value, or NULL when unset or empty: an empty export governs nothing.
const char* env_value(const char* name)
{
    const char* v = std::getenv(name);
    return (v && *v) ? v : NULL;
}

// The .manifest uses the input files' own layout: "[section]" then "key = value".
// A value may contain spaces (cpu_model, compiler) but never a newline.
typedef std::pair<std::string, std::string> Field;
typedef std::vector<Field> Fields;

void add(Fields& fs, const std::string& key, const std::string& value)
{
    fs.push_back(Field(key, value));
}

// A duration twice: "Nd HH:MM:SS" to read, the day part from one day up, then seconds.
void add_duration(Fields& fs, const std::string& name, double sec)
{
    const long long s = std::llround(sec);
    char buf[48];   // the longest, "106751d 23:59:59", is 16
    if (s >= 86400)
        std::snprintf(buf, sizeof(buf), "%lldd %02lld:%02lld:%02lld",
                      s / 86400, s % 86400 / 3600, s % 3600 / 60, s % 60);
    else
        std::snprintf(buf, sizeof(buf), "%02lld:%02lld:%02lld", s / 3600, s % 3600 / 60, s % 60);
    add(fs, name, buf);
    add(fs, name + "_sec", format_double("%.3f", sec));
}

// Unprobed = absent in the manifest; frames instead carry a fixed set with sentinels.
void add_section(Manifest& m, const std::string& name, const Fields& fs)
{
    if (fs.empty()) return;
    ManifestSection sec;
    sec.name = name;
    sec.fields = fs;
    m.push_back(sec);
}

void write_section(std::FILE* f, const std::string& section, const Fields& fs)
{
    std::fprintf(f, "[%s]\n", section.c_str());
    for (std::size_t i = 0; i < fs.size(); ++i)
        std::fprintf(f, "%s = %s\n", fs[i].first.c_str(), fs[i].second.c_str());
    std::fprintf(f, "\n");
}

// Provenance is diagnostic: a manifest that cannot be written warns, never aborts.
std::FILE* open_manifest(const std::string& filename, const char* mode, const char* lost)
{
    std::FILE* f = std::fopen(filename.c_str(), mode);
    if (f == NULL)
        std::cerr << "Warning: cannot open file '" << filename << "' for writing; "
                  << lost << " not recorded\n";
    return f;
}

// Check the error flag AND fclose: a record is smaller than the stdio buffer, so on a
// full disk ferror still reads clean while fclose fails and the record is lost.
void close_manifest(std::FILE* f, const std::string& filename)
{
    const bool write_failed = (std::ferror(f) != 0);
    const bool close_failed = (std::fclose(f) != 0);
    if (write_failed || close_failed)
        std::cerr << "Warning: failed writing to file '" << filename
                  << "'; run provenance may be incomplete\n";
}

// A key starts with a letter or '_', a compiler flag with '-': that tells a key=value
// payload from a bare flag list.
bool is_key_char(char c, bool first)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_'
        || (!first && ((c >= '0' && c <= '9') || c == '.' || c == '-'));
}

// Offset of the '=' closing a key that starts at i, or npos if none starts there.
std::size_t key_end_at(const std::string& s, std::size_t i)
{
    if (i >= s.size() || !is_key_char(s[i], true)) return std::string::npos;
    std::size_t j = i + 1;
    while (j < s.size() && is_key_char(s[j], false)) ++j;
    return (j < s.size() && s[j] == '=') ? j : std::string::npos;
}

// Splits a payload into pairs at the space that begins the NEXT key, since a value may
// hold spaces ("compiler=Apple LLVM 21.0.0 (clang-...)"). Empty for a bare flag list.
Fields parse_block_payload(const std::string& payload)
{
    Fields fs;
    std::size_t i = 0;
    while (i < payload.size()) {
        const std::size_t eq = key_end_at(payload, i);
        if (eq == std::string::npos) break;
        std::size_t end = eq + 1;
        while (end < payload.size()) {
            if (payload[end] == ' ' && key_end_at(payload, end + 1) != std::string::npos)
                break;
            ++end;
        }
        add(fs, payload.substr(i, eq - i), payload.substr(eq + 1, end - eq - 1));
        i = (end < payload.size()) ? end + 1 : end;
    }
    return fs;
}


