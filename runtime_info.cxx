// Free+inactive pages on macOS (free_count includes the speculative ones), MemAvailable
// on Linux: not comparable across the two.
double host_mem_avail_gib_now()
{
#if defined(__APPLE__)
    // mach_host_self() hands out a send right we own, unlike mach_task_self().
    const mach_port_t self = mach_host_self();
    vm_size_t page = 0;
    vm_statistics64_data_t vm;
    mach_msg_type_number_t count = HOST_VM_INFO64_COUNT;
    const bool ok = host_page_size(self, &page) == KERN_SUCCESS &&
                    host_statistics64(self, HOST_VM_INFO64,
                                      reinterpret_cast<host_info64_t>(&vm),
                                      &count) == KERN_SUCCESS;
    mach_port_deallocate(mach_task_self(), self);
    if (!ok) return 0;
    return (static_cast<double>(vm.free_count) + vm.inactive_count) * page / BYTES_PER_GIB;
#elif defined(__linux__)
    return read_proc_kb_gib("/proc/meminfo", "MemAvailable");
#else
    return 0;
#endif
}

namespace {

double host_mem_rss_gib()
{
#if defined(__APPLE__)
    mach_task_basic_info info;
    mach_msg_type_number_t count = MACH_TASK_BASIC_INFO_COUNT;
    if (task_info(mach_task_self(), MACH_TASK_BASIC_INFO,
                  reinterpret_cast<task_info_t>(&info), &count) != KERN_SUCCESS)
        return 0;
    return static_cast<double>(info.resident_size) / BYTES_PER_GIB;
#elif defined(__linux__)
    return read_proc_kb_gib("/proc/self/status", "VmRSS");
#else
    return 0;
#endif
}

// Bytes on macOS, kB on Linux, where the kernel also refreshes it lazily.
double ru_maxrss_gib()
{
#ifndef WIN32
    struct rusage ru;
    if (getrusage(RUSAGE_SELF, &ru) != 0) return 0;
#if defined(__APPLE__)
    return static_cast<double>(ru.ru_maxrss) / BYTES_PER_GIB;
#else
    return static_cast<double>(ru.ru_maxrss) / KIB_PER_GIB;
#endif
#else
    return 0;
#endif
}

} // namespace

double sample_rss_gib(double& peak_rss_gib)
{
    const double rss_gib = host_mem_rss_gib();
    peak_rss_gib = std::max(peak_rss_gib, std::max(ru_maxrss_gib(), rss_gib));
    return rss_gib;
}

double process_cpu_time_sec()
{
#ifndef WIN32
    struct rusage ru;
    if (getrusage(RUSAGE_SELF, &ru) != 0) return 0;
    return ru.ru_utime.tv_sec + ru.ru_utime.tv_usec * 1e-6
         + ru.ru_stime.tv_sec + ru.ru_stime.tv_usec * 1e-6;
#else
    return 0;
#endif
}

