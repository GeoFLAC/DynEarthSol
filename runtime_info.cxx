void report_build_snapshot()
{
    std::istringstream block(snapshot_sentinel);
    std::string line;
    while (std::getline(block, line)) {
        const std::size_t key_end = line.find(' ');
        const std::size_t sep = line.find(": ");
        const std::size_t dot = line.rfind('.', key_end);
        if (sep != std::string::npos && dot != std::string::npos) {
            const std::string topic = line.substr(dot + 1, key_end - dot - 1);
            std::cout << "[build][" << topic << "] " << line.substr(sep + 2);
            // The block cannot carry its own link time; the host line closes it,
            // so build_utc joins here exactly as it does in the .manifest.
            if (topic == "host") std::cout << " build_utc=" << exe_mtime_utc();
            std::cout << '\n';
        }
        else
            std::cout << line << '\n';
    }
#ifdef DES_HAS_CODE_DIFF
    // nvc++ discards an array nothing references, whatever __attribute__((used))
    // says, so the payload needs a volatile reference the optimizer cannot fold away.
    const char* volatile keep_code_diff = snapshot_code_diff;
    (void)keep_code_diff;
    std::cout << "[build][code-changes] embedded -- see -h for the extraction\n";
#endif
}
